#include "umicom/ai/training/generation_cache.h"
#include "umicom/ai/training/checkpoint.h"
#include "umicom/ai/training/byte_tokenizer.h"

#include <inttypes.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

int main(int argc, char **argv)
{
    UmiAiTrainingDecoderConfig configuration = {
        UMI_AI_BYTE_VOCABULARY, 8U, 8U, 16U, 2U, UINT64_C(20261023)
    };
    const UmiAiTrainingNucleusOptions policy = {0.90F, 12U, 0.90F};
    const uint8_t prompt[] = { (uint8_t)'i', (uint8_t)'n', (uint8_t)'t', (uint8_t)' ' };
    UmiAiTrainingGenerationCacheStats statistics = {0};
    UmiAiTrainingDecoder *decoder = NULL;
    uint8_t canonical[16] = {0};
    uint8_t cached[16] = {0};
    size_t canonicalCount = 0U, cachedCount = 0U;
    UmiStatus status;

    if (argc != 1 && argc != 2) {
        fputs("usage: umicom-native-llm-kv-nucleus-demo [reviewed-decoder-checkpoint]\n", stderr);
        return 2;
    }
    if (argc == 2)
        status = UmiAiTrainingDecoderCheckpointLoadFile(argv[1], &decoder);
    else
        status = UmiAiTrainingDecoderCreate(&configuration, &decoder);
    if (status != UMI_STATUS_OK) {
        fprintf(stderr, "could not load reviewed decoder (status=%d)\n", (int)status);
        return 1;
    }

    status = UmiAiTrainingDecoderGenerateBytesNucleus(decoder,
        prompt, sizeof prompt, &policy, sizeof canonical, UINT64_C(4488),
        canonical, sizeof canonical, &canonicalCount);
    if (status == UMI_STATUS_OK)
        status = UmiAiTrainingDecoderGenerateCachedBytesNucleus(decoder,
            prompt, sizeof prompt, &policy, sizeof cached, UINT64_C(4488),
            cached, sizeof cached, &cachedCount, &statistics);
    if (status != UMI_STATUS_OK || canonicalCount != cachedCount ||
        memcmp(canonical, cached, sizeof cached) != 0) {
        fprintf(stderr, "canonical/KV-cache generation differs (status=%d)\n", (int)status);
        UmiAiTrainingDecoderDestroy(decoder);
        return 1;
    }
    printf("Verified %zu byte-for-byte generated tokens\n", cachedCount);
    printf("Computed token rows: %" PRIu64 "\n", statistics.computedRows);
    printf("Full rolling-window rebuilds: %" PRIu64 "\n", statistics.windowRebuilds);
    printf("Retained context tokens: %zu\n", statistics.retainedTokens);
    fputs("Generated bytes (hex, not executable code): ", stdout);
    for (size_t index = 0U; index < cachedCount; ++index)
        printf("%02x", (unsigned)cached[index]);
    putchar('\n');
    UmiAiTrainingDecoderDestroy(decoder);
    return 0;
}
