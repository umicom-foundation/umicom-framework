#include "umicom/education/pe_imports.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Decode only hexadecimal fixture characters; whitespace is handled by the caller. */
static int Hex(unsigned char c)
{
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    return -1;
}

/* Public null/size failures preserve a previously initialized result object. */
static int Arguments(void)
{
    UmiEducationPeImports out, before;
    memset(&out, 0xa5, sizeof(out)); memcpy(&before, &out, sizeof(out));
    unsigned char data[64] = {0};
    if (UmiEducationPeImportsInspectBytes(NULL, 64U, &out) != UMI_STATUS_INVALID_ARGUMENT ||
        UmiEducationPeImportsInspectBytes(data, 64U, NULL) != UMI_STATUS_INVALID_ARGUMENT ||
        UmiEducationPeImportsInspectBytes(data, 0U, &out) != UMI_STATUS_PARSE_ERROR ||
        UmiEducationPeImportsInspectBytes(data, (size_t)UMI_PE_IMPORT_IMAGE_LIMIT + 1U, &out) != UMI_STATUS_CAPACITY_EXCEEDED ||
        memcmp(&out, &before, sizeof(out)) != 0) return 1;
    return 0;
}

/* Parse one finite fixture document and compare ordered names, architecture and
 * refusal behaviour. No expected value is generated by the function under test. */
int main(int argc, char **argv)
{
    if (argc == 2 && strcmp(argv[1], "--arguments") == 0) return Arguments();
    if (argc != 2) return 2;
    FILE *file = fopen(argv[1], "rb");
    if (file == NULL) return 2;
    unsigned char *data = malloc(1024U * 1024U);
    UmiEducationPeImports *out = malloc(sizeof(*out)), *before = malloc(sizeof(*before));
    if (data == NULL || out == NULL || before == NULL) {
        free(data); free(out); free(before); (void)fclose(file); return 2;
    }
    char line[2048], expected[65536] = "";
    size_t size = 0U;
    int mode = 0, expect = -1, invalid = 0;
    unsigned machine = 0U;
    while (fgets(line, sizeof(line), file) != NULL) {
        size_t n = strlen(line);
        while (n > 0U && (line[n-1U] == '\n' || line[n-1U] == '\r')) line[--n] = '\0';
        if (!mode) {
            if (strcmp(line, "data:") == 0) mode = 1;
            else if (strcmp(line, "expect=ok") == 0) expect = 1;
            else if (strcmp(line, "expect=error") == 0) expect = 0;
            else if (strncmp(line, "machine=", 8U) == 0) {
                if (sscanf(line + 8U, "%x", &machine) != 1) invalid = 1;
            } else if (strncmp(line, "imports=", 8U) == 0) {
                if (n - 8U >= sizeof(expected)) invalid = 1;
                else memcpy(expected, line + 8U, n - 8U + 1U);
            }
            continue;
        }
        if (n % 2U != 0U || n / 2U > 1024U * 1024U - size) { invalid = 1; break; }
        for (size_t i = 0U; i < n; i += 2U) {
            int hi = Hex((unsigned char)line[i]), lo = Hex((unsigned char)line[i + 1U]);
            if (hi < 0 || lo < 0) { invalid = 1; break; }
            data[size++] = (unsigned char)((unsigned)hi * 16U + (unsigned)lo);
        }
    }
    if (ferror(file) || fclose(file) != 0 || expect < 0 || !mode) invalid = 1;
    memset(out, 0xa5, sizeof(*out)); memcpy(before, out, sizeof(*out));
    UmiStatus status = invalid ? UMI_STATUS_INTERNAL_ERROR : UmiEducationPeImportsInspectBytes(data, size, out);
    int failed = invalid || ((status == UMI_STATUS_OK) != expect);
    if (status != UMI_STATUS_OK) {
        if (memcmp(out, before, sizeof(*out)) != 0) failed = 1;
    } else {
        if ((unsigned)out->machine != machine) failed = 1;
        size_t offset = 0U;
        for (size_t i = 0U; i < out->count; ++i) {
            size_t length = strlen(out->names[i]);
            if (strncmp(expected + offset, out->names[i], length) != 0) { failed = 1; break; }
            offset += length;
            if (i + 1U < out->count) {
                if (expected[offset] != '|') { failed = 1; break; }
                ++offset;
            }
        }
        if (expected[offset] != '\0') failed = 1;
    }
    if (failed) (void)fprintf(stderr, "%s: status=%d expected=%d invalid=%d\n", argv[1], (int)status, expect, invalid);
    free(data); free(out); free(before);
    return failed;
}
