#include "umicom/ai/training/generation_session.h"
#include "umicom/ai/training/byte_tokenizer.h"
#include "umicom/ai/training/checkpoint.h"

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CHECK(expression) do { if (!(expression)) { \
    fprintf(stderr, "line %d: %s\n", __LINE__, #expression); \
    return 1; } } while (0)

int main(void)
{
    const UmiAiTrainingDecoderConfig config = {
        UMI_AI_BYTE_VOCABULARY, 8U, 8U, 16U, 2U, UINT64_C(20261023)
    };
    const UmiAiTrainingNucleusOptions policies[] = {
        {1.0F, 1U, 1.0F},
        {0.8F, 11U, 1.0F},
        {0.9F, 12U, 0.91F}
    };
    const size_t prompt[] = {109U, 114U, 120U, 36U, 39U, 101U,
        102U, 10U, 11U, 12U, 13U, 14U, 15U, 16U, 17U, 18U};
    const size_t lengths[] = {0U, 1U, 3U, 8U, 16U};
    UmiAiTrainingDecoder *model = NULL;
    uint8_t *before = NULL, *after = NULL;
    size_t checkpointBytes = 0U, written = 0U;

    CHECK(UmiAiTrainingDecoderCreate(&config, &model) == UMI_STATUS_OK);
    CHECK(UmiAiTrainingDecoderCheckpointSize(model, &checkpointBytes) == UMI_STATUS_OK);
    before = malloc(checkpointBytes);
    after = malloc(checkpointBytes);
    CHECK(before != NULL && after != NULL);
    CHECK(UmiAiTrainingDecoderCheckpointEncode(model, before,
        checkpointBytes, &written) == UMI_STATUS_OK && written == checkpointBytes);

    for (size_t policyIndex = 0U; policyIndex < 3U; ++policyIndex) {
        for (size_t promptIndex = 0U; promptIndex < 5U; ++promptIndex) {
            UmiAiTrainingGenerationSession *session = NULL;
            UmiAiTrainingGenerationCacheStats oneShotStats = {0}, streamedStats = {0};
            size_t canonical[24] = {0}, cached[24] = {0}, streamed[24] = {0};
            size_t count = 0U, generated = 999U, observed = 0U;
            size_t promptLength = lengths[promptIndex];
            const size_t *promptPtr = promptLength == 0U ? NULL : prompt;
            CHECK(UmiAiTrainingDecoderGenerateNucleus(model, promptPtr,
                promptLength, &policies[policyIndex], 24U, UINT64_C(1717),
                canonical, 24U, &count) == UMI_STATUS_OK && count == 24U);
            CHECK(UmiAiTrainingDecoderGenerateCachedNucleus(model, promptPtr,
                promptLength, &policies[policyIndex], 24U, UINT64_C(1717),
                cached, 24U, &count, &oneShotStats) == UMI_STATUS_OK && count == 24U);
            CHECK(UmiAiTrainingGenerationSessionCreate(model, promptPtr,
                promptLength, &policies[policyIndex], UINT64_C(1717),
                &session) == UMI_STATUS_OK);
            CHECK(session != NULL);
            CHECK(UmiAiTrainingGenerationSessionInspect(session,
                &generated, &streamedStats) == UMI_STATUS_OK);
            CHECK(generated == 0U && streamedStats.retainedTokens == 8U);
            CHECK(streamedStats.windowRebuilds == 0U);
            /* Separate calls simulate UI pulls in unequal batches. Neither
             * schedule nor pauses can reseed or discard earlier KV rows. */
            for (size_t i = 0U; i < 24U; ++i) {
                CHECK(UmiAiTrainingGenerationSessionNext(session,
                    &streamed[i]) == UMI_STATUS_OK);
                if (i == 2U || i == 9U || i == 23U) {
                    CHECK(UmiAiTrainingGenerationSessionInspect(session,
                        &generated, &streamedStats) == UMI_STATUS_OK);
                    CHECK(generated == i + 1U);
                }
            }
            CHECK(UmiAiTrainingGenerationSessionInspect(session,
                &observed, &streamedStats) == UMI_STATUS_OK);
            CHECK(observed == 24U && streamedStats.windowRebuilds == 23U);
            CHECK(streamedStats.retainedTokens == 8U);
            CHECK(streamedStats.computedRows == oneShotStats.computedRows);
            CHECK(memcmp(streamed, cached, sizeof streamed) == 0);
            CHECK(memcmp(streamed, canonical, sizeof streamed) == 0);
            UmiAiTrainingGenerationSessionDestroy(session);
        }
    }

    /* Every 0x00/0xff byte remains an ordinary generated byte. Decoder/byte
     * semantics are identical whether returned one byte at a time or in bulk. */
    {
        const uint8_t bytePrompt[] = {0U, 0xFFU, 0x80U, (uint8_t)'A'};
        uint32_t byteIds[sizeof bytePrompt];
        size_t tokenIds[sizeof bytePrompt], count = 0U, generated = 0U;
        uint8_t bulk[16] = {0}, pulled[16] = {0};
        UmiAiTrainingGenerationSession *session = NULL;
        CHECK(UmiAiByteEncode(bytePrompt, sizeof bytePrompt, byteIds,
            sizeof byteIds / sizeof byteIds[0], &count) == UMI_STATUS_OK);
        for (size_t i = 0U; i < count; ++i) tokenIds[i] = (size_t)byteIds[i];
        CHECK(UmiAiTrainingDecoderGenerateCachedBytesNucleus(model,
            bytePrompt, sizeof bytePrompt, &policies[2], 16U, UINT64_C(8899),
            bulk, sizeof bulk, &count, NULL) == UMI_STATUS_OK && count == 16U);
        CHECK(UmiAiTrainingGenerationSessionCreate(model, tokenIds,
            sizeof bytePrompt, &policies[2], UINT64_C(8899), &session) == UMI_STATUS_OK);
        for (size_t i = 0U; i < 16U; ++i) {
            CHECK(UmiAiTrainingGenerationSessionNextByte(session,
                &pulled[i]) == UMI_STATUS_OK);
        }
        CHECK(memcmp(bulk, pulled, sizeof bulk) == 0);
        CHECK(UmiAiTrainingGenerationSessionInspect(session,
            &generated, &(UmiAiTrainingGenerationCacheStats){0}) == UMI_STATUS_OK);
        CHECK(generated == 16U);
        UmiAiTrainingGenerationSessionDestroy(session);
    }

    CHECK(UmiAiTrainingDecoderCheckpointEncode(model, after,
        checkpointBytes, &written) == UMI_STATUS_OK && written == checkpointBytes);
    CHECK(memcmp(before, after, checkpointBytes) == 0);
    free(after);
    free(before);
    UmiAiTrainingDecoderDestroy(model);
    puts("native C23 stream / cached / canonical parity and checkpoint stability: PASS");
    return 0;
}
